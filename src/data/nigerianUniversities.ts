/**
 * Storage key for user/admin customized group links in local device
 */
const GROUP_LINKS_STORAGE_KEY = 'jambix_university_grouplinks_v1';

/**
 * Retrieves custom overrides stored locally on device
 */
export function getSavedCustomGroupLinks(): Record<string, string> {
  if (typeof window === 'undefined') return {};
  try {
    const raw = localStorage.getItem(GROUP_LINKS_STORAGE_KEY);
    return raw ? JSON.parse(raw) : {};
  } catch (e) {
    console.error('Failed to read custom group links:', e);
    return {};
  }
}

/**
 * Saves or updates a custom group link for any university
 */
export function saveCustomGroupLink(uniId: string, link: string): void {
  if (typeof window === 'undefined') return;
  try {
    const current = getSavedCustomGroupLinks();
    if (link.trim()) {
      current[uniId] = link.trim();
    } else {
      delete current[uniId];
    }
    localStorage.setItem(GROUP_LINKS_STORAGE_KEY, JSON.stringify(current));
  } catch (e) {
    console.error('Failed to save custom group link:', e);
  }
}

/**
 * Returns the effective group link for a university by combining:
 * 1. Local saved overrides (instant real-time editing)
 * 2. Static UNIVERSITY_GROUP_LINKS config
 */
export function getUniversityGroupLink(uniId: string): string {
  const custom = getSavedCustomGroupLinks();
  if (custom[uniId]) return custom[uniId];
  return UNIVERSITY_GROUP_LINKS[uniId] || '';
}

/**
 * Returns all universities with their effective group links merged
 */
export function getUniversitiesList(): University[] {
  const custom = getSavedCustomGroupLinks();
  return RAW_NIGERIAN_UNIVERSITIES.map((uni) => ({
    ...uni,
    groupLink: custom[uni.id] || UNIVERSITY_GROUP_LINKS[uni.id] || uni.groupLink || '',
  }));
}
